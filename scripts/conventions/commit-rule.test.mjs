import { describe, expect, it } from 'vitest';

import { checkCommitMessage } from './commit-rule.mjs';

const expectValid = (message) => {
  expect(checkCommitMessage(message)).toEqual({ valid: true, errors: [] });
};

const expectInvalid = (message, errorPattern) => {
  const result = checkCommitMessage(message);
  expect(result.valid).toBe(false);
  expect(result.errors.join('\n')).toMatch(errorPattern);
};

describe('commit rule', () => {
  describe('given a header in the "<gitmoji> <Title>" format', () => {
    it.each([
      '✨ Add exposure filter to the graph view',
      '🐛 Fix trace skipping NAT hops',
      '♿️ Improve keyboard focus in the detail panel',
      '🔖 Release v0.1.0',
      '🧑‍💻 Improve the developer setup',
    ])('accepts %s', (message) => {
      expectValid(message);
    });
  });

  describe('given a gitmoji written with or without the U+FE0F variation selector', () => {
    it('accepts the variant without U+FE0F', () => {
      expectValid('♿ Improve keyboard focus in the detail panel');
    });

    it('accepts the variant with U+FE0F', () => {
      expectValid('♿️ Improve keyboard focus in the detail panel');
    });

    it('accepts a gitmoji that the list stores without U+FE0F when written with it', () => {
      expectValid('✅️ Add tests for the trace');
    });
  });

  describe('given a header without a valid gitmoji', () => {
    it('rejects a missing gitmoji', () => {
      expectInvalid('added stuff', /gitmoji/i);
    });

    it('rejects a gitmoji shortcode instead of the unicode emoji', () => {
      expectInvalid(':sparkles: Add graph filters', /gitmoji/i);
    });

    it('rejects an emoji that is not in the gitmoji list', () => {
      expectInvalid('🥔 Add graph filters', /gitmoji/i);
    });
  });

  describe('given the separator between gitmoji and title', () => {
    it('rejects a missing space', () => {
      expectInvalid('✨Add graph filters', /single space/i);
    });

    it('rejects more than one space', () => {
      expectInvalid('✨  Add graph filters', /single space/i);
    });

    it('rejects an empty title', () => {
      expectInvalid('✨ ', /title/i);
    });
  });

  describe('given the title casing and punctuation', () => {
    it('rejects a title starting with a lowercase letter', () => {
      expectInvalid('✨ add graph filters', /capital/i);
    });

    it('rejects a trailing period', () => {
      expectInvalid('✨ Add graph filters.', /period/i);
    });
  });

  describe('given the "If applied, this commit would …" mood', () => {
    it.each([
      ['✨ Added graph filters', /imperative/i],
      ['✨ Adding graph filters', /imperative/i],
      ['✨ Adds graph filters', /imperative/i],
      ['🐛 Fixes trace skipping NAT hops', /imperative/i],
      ['📝 Updates the README', /imperative/i],
    ])('rejects %s', (message, pattern) => {
      expectInvalid(message, pattern);
    });

    it.each([
      '⚡️ Speed up the graph layout',
      '🌱 Seed the demo workspace',
      '✨ Embed the trace in the detail panel',
      '✨ Bring back the minimap',
      '✨ Ping hosts from the status watcher',
      '♻️ String together trace steps',
      '🔧 Need a setup token for the first admin',
    ])('accepts the allowlisted imperative verb in %s', (message) => {
      expectValid(message);
    });
  });

  describe('given the header length, counted in graphemes', () => {
    const titleOfLength = (length) => `A${'b'.repeat(length - 1)}`;

    it('accepts 79 graphemes even when the gitmoji spans several code units', () => {
      // ♿️ is 2 UTF-16 code units but 1 grapheme: 1 + 1 space + 77 = 79.
      expectValid(`♿️ ${titleOfLength(77)}`);
    });

    it('rejects 80 graphemes', () => {
      expectInvalid(`✨ ${titleOfLength(78)}`, /80/);
    });
  });

  describe('given a body', () => {
    it('accepts a body separated by a blank line', () => {
      expectValid('✨ Add graph filters\n\nFilters by protocol and exposure.\n\nCo-Authored-By: Someone <a@b.c>');
    });

    it('rejects a body that is not separated by a blank line', () => {
      expectInvalid('✨ Add graph filters\nFilters by protocol.', /blank line/i);
    });

    it('ignores git comment lines', () => {
      expectValid('✨ Add graph filters\n# Please enter the commit message for your changes.\n# On branch feature-x');
    });
  });

  describe('given an empty message', () => {
    it('rejects it', () => {
      expectInvalid('', /empty/i);
    });

    it('rejects a message made only of comments', () => {
      expectInvalid('# Please enter the commit message\n', /empty/i);
    });
  });

  describe('given a message generated by git or GitHub for a merge', () => {
    it.each([
      'Merge branch \'develop\' into feature-graph-filters',
      'Merge remote-tracking branch \'origin/develop\' into feature-graph-filters',
      'Merge pull request #12 from MrStanDu33/develop',
    ])('accepts %s', (message) => {
      expectValid(message);
    });
  });
});
