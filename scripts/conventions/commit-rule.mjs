import { gitmojis } from 'gitmojis';

/** The header must be shorter than this many graphemes. */
export const MAX_HEADER_GRAPHEMES = 80;

const VARIATION_SELECTOR = /\uFE0F/gu;

const normalizeEmoji = (emoji) => emoji.replace(VARIATION_SELECTOR, '');

/** Gitmoji (without U+FE0F) → semver level: 'major', 'minor', 'patch' or null. */
const GITMOJIS = new Map(gitmojis.map(({ emoji, semver }) => [normalizeEmoji(emoji), semver]));

/** Imperative verbs that end in -ed or -ing and must not be mistaken for past tense or gerunds. */
export const IMPERATIVE_ALLOWLIST = new Set([
  'bleed', 'breed', 'embed', 'exceed', 'feed', 'heed', 'need', 'proceed', 'reseed', 'seed', 'shed', 'shred',
  'speed', 'succeed', 'weed',
  'bring', 'cling', 'fling', 'ping', 'ring', 'sing', 'sling', 'spring', 'sting', 'string', 'swing', 'wring',
]);

/** Common third-person forms that do not read as "If applied, this commit would …". */
export const THIRD_PERSON_DENYLIST = new Set([
  'adds', 'allows', 'bumps', 'changes', 'cleans', 'converts', 'creates', 'deletes', 'disables', 'documents',
  'downgrades', 'enables', 'ensures', 'fixes', 'handles', 'implements', 'improves', 'introduces', 'makes',
  'merges', 'migrates', 'moves', 'prevents', 'refactors', 'removes', 'renames', 'replaces', 'reverts', 'sets',
  'supports', 'updates', 'upgrades', 'uses',
]);

/** Messages generated by git or GitHub for merges are exempt. */
const GENERATED_MERGE = /^Merge (branch|remote-tracking branch|pull request) /;

const segmenter = new Intl.Segmenter('en', { granularity: 'grapheme' });

const graphemes = (text) => [...segmenter.segment(text)].map(({ segment }) => segment);

/**
 * Splits a "<gitmoji> <Title>" header.
 *
 * @param {string} header
 * @returns {{ emoji: string, semver: string | null, title: string } | null} null when it has no gitmoji.
 */
export const parseHeader = (header) => {
  const [emoji = '', ...rest] = graphemes(header);
  const normalized = normalizeEmoji(emoji);
  if (!GITMOJIS.has(normalized)) {
    return null;
  }
  return { emoji, semver: GITMOJIS.get(normalized) ?? null, title: rest.join('').trim() };
};

const FORMAT_HINT = 'Expected "<gitmoji> <Title>", e.g. "✨ Add exposure filter to the graph view".';

const checkMood = (title) => {
  const firstWord = title.split(' ')[0].toLowerCase();
  if (IMPERATIVE_ALLOWLIST.has(firstWord)) {
    return [];
  }
  if (firstWord.endsWith('ed') || firstWord.endsWith('ing') || THIRD_PERSON_DENYLIST.has(firstWord)) {
    return [
      `"${title.split(' ')[0]}" is not imperative. The title must complete "If applied, this commit would …"`
      + ' (e.g. "Add", "Fix", "Update").',
    ];
  }
  return [];
};

const checkTitle = (title) => {
  if (title.length === 0) {
    return ['The title after the gitmoji is empty.'];
  }
  const errors = [];
  if (!/^\p{Lu}/u.test(title)) {
    errors.push('The title must start with a capital letter.');
  }
  if (title.endsWith('.')) {
    errors.push('The title must not end with a period.');
  }
  return [...errors, ...checkMood(title)];
};

const checkHeader = (header) => {
  const [emoji = '', ...rest] = graphemes(header);
  if (!GITMOJIS.has(normalizeEmoji(emoji))) {
    return [`The header must start with a gitmoji (unicode emoji from gitmoji.dev). ${FORMAT_HINT}`];
  }

  const errors = [];
  const length = rest.length + 1;
  if (length >= MAX_HEADER_GRAPHEMES) {
    errors.push(`The header must be shorter than ${MAX_HEADER_GRAPHEMES} characters (it has ${length}).`);
  }

  const afterEmoji = rest.join('');
  if (!afterEmoji.startsWith(' ') || afterEmoji.startsWith('  ')) {
    errors.push(`Use a single space between the gitmoji and the title. ${FORMAT_HINT}`);
    return errors;
  }
  return [...errors, ...checkTitle(afterEmoji.slice(1))];
};

/**
 * Checks a commit message against the project convention.
 *
 * @param {string} message Raw commit message, as git writes it to COMMIT_EDITMSG.
 * @returns {{ valid: boolean, errors: string[] }}
 */
export const checkCommitMessage = (message) => {
  const lines = message
    .split('\n')
    .filter((line) => !line.startsWith('#'));
  while (lines.length > 0 && lines.at(-1).trim() === '') {
    lines.pop();
  }

  const [header = ''] = lines;
  if (header.trim() === '') {
    return { valid: false, errors: ['The commit message is empty.'] };
  }
  if (GENERATED_MERGE.test(header)) {
    return { valid: true, errors: [] };
  }

  const errors = checkHeader(header);
  if (lines.length > 1 && lines[1].trim() !== '') {
    errors.push('Separate the header from the body with a blank line.');
  }
  return { valid: errors.length === 0, errors };
};
